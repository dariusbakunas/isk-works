    assert!(!f.contains("INDEX(Ledger_"), "no whole-column ledger INDEX");
    // (L) Check cross-checks the ledger's independent recipe recompute
    // (col T), not its allocator Excel Required (which is this cell).
    assert!(
        f.contains("$I20='Allocation Ledger'!$T$2"),
        "Check vs ledger recompute: {f}"
    );

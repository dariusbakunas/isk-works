async fn post_export(
    app: axum::Router,
    build_id: BuildId,
    body: serde_json::Value,
) -> (StatusCode, axum::http::HeaderMap, Vec<u8>) {
    let response = app
        .oneshot(
            Request::builder()
                .method("POST")
                .uri(format!("/api/builds/{}/export-verification", build_id.0))
                .header("content-type", "application/json")
                .body(Body::from(body.to_string()))
                .unwrap(),
        )
        .await
        .unwrap();
    let status = response.status();
    let headers = response.headers().clone();
    let bytes = to_bytes(response.into_body(), usize::MAX)
        .await
        .unwrap()
        .to_vec();
    (status, headers, bytes)
}

fn open(bytes: &[u8]) -> Xlsx<Cursor<Vec<u8>>> {
    calamine::open_workbook_from_rs(Cursor::new(bytes.to_vec()))
        .expect("generated bytes parse as a valid .xlsx workbook")
}

fn sheet_names(wb: &Xlsx<Cursor<Vec<u8>>>) -> Vec<String> {
    wb.sheet_names().iter().map(|s| s.to_string()).collect()
}

fn cell_text(data: &Data) -> String {
    match data {
        Data::String(s) => s.clone(),
        Data::Float(f) => f.to_string(),
        Data::Int(i) => i.to_string(),
        Data::Bool(b) => b.to_string(),
        _ => String::new(),
    }
}
fn cell_f64(data: &Data) -> Option<f64> {
    match data {
        Data::Float(f) => Some(*f),
        Data::Int(i) => Some(*i as f64),
        Data::String(s) => s.parse().ok(),
        Data::Bool(b) => Some(if *b { 1.0 } else { 0.0 }),
        _ => None,
    }
}

/// header -> value map for the first data row whose `key_header` == `key`.
fn table_row(
    wb: &mut Xlsx<Cursor<Vec<u8>>>,
    sheet: &str,
    key_header: &str,
    key: &str,
) -> std::collections::HashMap<String, Data> {
    let range = wb
        .worksheet_range(sheet)
        .unwrap_or_else(|_| panic!("sheet {sheet} exists"));
    let headers: Vec<String> = range
        .rows()
        .next()
        .expect("header row")
        .iter()
        .map(cell_text)
        .collect();
    let key_col = headers
        .iter()
        .position(|h| h == key_header)
        .unwrap_or_else(|| panic!("column {key_header} on sheet {sheet}"));
    for row in range.rows().skip(1) {
        if row.get(key_col).map(cell_text).as_deref() == Some(key) {
            return headers.iter().cloned().zip(row.iter().cloned()).collect();
        }
    }
    panic!("no row on {sheet} with {key_header} == {key}");
}

/// Like `table_row`, but for an operation sheet whose material table
/// header sits at 0-based row 18 (below the key/value header block).
fn op_table_row(
    wb: &mut Xlsx<Cursor<Vec<u8>>>,
    sheet: &str,
    type_id: &str,
) -> std::collections::HashMap<String, Data> {
    let range = wb.worksheet_range(sheet).unwrap();
    let rows: Vec<&[Data]> = range.rows().collect();
    let headers: Vec<String> = rows[18].iter().map(cell_text).collect();
    for row in &rows[19..] {
        if row.first().map(cell_text).as_deref() == Some(type_id) {
            return headers.iter().cloned().zip(row.iter().cloned()).collect();
        }
    }
    panic!("no material row on {sheet} for type {type_id}");
}

fn headers_of(wb: &mut Xlsx<Cursor<Vec<u8>>>, sheet: &str) -> Vec<String> {
    wb.worksheet_range(sheet)
        .unwrap()
        .rows()
        .next()
        .unwrap()
        .iter()
        .map(cell_text)
        .collect()
}

/// Sheet display-name -> its `xl/worksheets/sheetN.xml`, resolved through
/// `xl/workbook.xml` + its rels. (calamine's `worksheet_formula` is
/// unreliable for our workbooks, so formula assertions read the XML.)
fn sheet_xml_map(bytes: &[u8]) -> std::collections::HashMap<String, String> {
    let mut archive = zip::ZipArchive::new(Cursor::new(bytes.to_vec())).unwrap();
    let read = |archive: &mut zip::ZipArchive<Cursor<Vec<u8>>>, name: &str| -> String {
        let mut f = archive.by_name(name).unwrap();
        let mut s = String::new();
        f.read_to_string(&mut s).unwrap();
        s
    };
    let workbook_xml = read(&mut archive, "xl/workbook.xml");
    let rels_xml = read(&mut archive, "xl/_rels/workbook.xml.rels");
    // rId -> target file
    let mut rid_target: std::collections::HashMap<String, String> =
        std::collections::HashMap::new();
    for chunk in rels_xml.split("<Relationship ").skip(1) {
        let id = attr(chunk, "Id");
        let target = attr(chunk, "Target");
        if let (Some(id), Some(target)) = (id, target) {
            rid_target.insert(id, target.trim_start_matches('/').to_string());
        }
    }
    let mut out = std::collections::HashMap::new();
    for chunk in workbook_xml.split("<sheet ").skip(1) {
        let name = attr(chunk, "name");
        let rid = chunk
            .split("r:id=\"")
            .nth(1)
            .and_then(|s| s.split('"').next())
            .map(str::to_string);
        if let (Some(name), Some(rid)) = (name, rid) {
            if let Some(target) = rid_target.get(&rid) {
                let path = if target.starts_with("xl/") {
                    target.clone()
                } else {
                    format!("xl/{target}")
                };
                let xml = read(&mut archive, &path);
                out.insert(name, unescape_xml(&xml));
            }
        }
    }
    out
}

fn attr(chunk: &str, key: &str) -> Option<String> {
    chunk
        .split(&format!("{key}=\""))
        .nth(1)
        .and_then(|s| s.split('"').next())
        .map(str::to_string)
}

fn unescape_xml(s: &str) -> String {
    s.replace("&gt;", ">")
        .replace("&lt;", "<")
        .replace("&quot;", "\"")
        .replace("&apos;", "'")
        .replace("&amp;", "&")
}

/// All `<f>...</f>` formula bodies on `sheet`, unescaped, joined by `\n`.
fn sheet_formulas(bytes: &[u8], sheet: &str) -> String {
    let xml = sheet_xml_map(bytes).remove(sheet).unwrap_or_default();
    xml.split("<f>")
        .skip(1)
        .filter_map(|s| s.split("</f>").next())
        .collect::<Vec<_>>()
        .join("\n")
}

/// The formula body of the cell at Excel `col_letter``row1` on `sheet`,
/// or "" if that cell is not a formula.
fn formula_cell(bytes: &[u8], sheet: &str, cell_ref: &str) -> String {
    let xml = sheet_xml_map(bytes).remove(sheet).unwrap_or_default();
    let needle = format!("<c r=\"{cell_ref}\"");
    let Some(rest) = xml.split(&needle).nth(1) else {
        return String::new();
    };
    let Some(cell) = rest.split("</c>").next() else {
        return String::new();
    };
    cell.split("<f>")
        .nth(1)
        .and_then(|s| s.split("</f>").next())
        .unwrap_or("")
        .to_string()
}

/// Row index of the first Operations row whose `Op #` == `op_index`, then
/// the value of `header` on that row.
fn ops_value(wb: &mut Xlsx<Cursor<Vec<u8>>>, op_index: u32, header: &str) -> Data {
    table_row(wb, "Operations", "Op #", &op_index.to_string())
        .remove(header)
        .unwrap()
}

fn all_worksheet_xml(bytes: &[u8]) -> String {
    let mut archive = zip::ZipArchive::new(Cursor::new(bytes.to_vec())).unwrap();
    let mut out = String::new();
    for i in 0..archive.len() {
        let mut file = archive.by_index(i).unwrap();
        if file.name().starts_with("xl/worksheets/sheet") {
            let mut buf = String::new();
            file.read_to_string(&mut buf).unwrap();
            out.push_str(&buf);
        }
    }
    out
}

fn sheet1_xml(bytes: &[u8]) -> String {
    let mut archive = zip::ZipArchive::new(Cursor::new(bytes.to_vec())).unwrap();
    let mut file = archive.by_name("xl/worksheets/sheet1.xml").unwrap();
    let mut buf = String::new();
    file.read_to_string(&mut buf).unwrap();
    buf
}

/// The op sheet names, in workbook order (between "Materials" and
/// "Allocation Ledger").
fn op_sheet_names(wb: &Xlsx<Cursor<Vec<u8>>>) -> Vec<String> {
    let names = sheet_names(wb);
    let start = names.iter().position(|n| n == "Materials").unwrap() + 1;
    let end = names.iter().position(|n| n == "Allocation Ledger").unwrap();
    names[start..end].to_vec()
}


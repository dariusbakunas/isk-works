// -- The whole HTTP pipeline (route -> materials_with_planning_cost
// -> VerificationExportModel -> workbook) wires the cost projection
// end-to-end -- cost columns exist, and a priced all-Buy leaf's numbers
// agree between the API evidence and what Excel is given to compute
// from.
#[tokio::test]
async fn export_cost_columns_are_wired_end_to_end_through_the_http_route() {
    let (parent, _ws, owner_id) = rifter_root(1);
    let parent_id = parent.id;
    let (app, _inv) = export_app_priced(parent, owner_id, Vec::new(), seeded(vec![(34, 60)]));
    let (status, _h, bytes) = post_export(app, parent_id, overlay(1, serde_json::json!([]))).await;
    assert_eq!(status, StatusCode::OK);

    let mut wb = open(&bytes);
    let ops_headers = headers_of(&mut wb, "Operations");
    for h in [
        "Excel Material Cost",
        "API Material Cost",
        "Material Cost Delta",
        "Excel Installation",
        "API Installation",
        "Excel Total Cost",
        "Cost Check",
    ] {
        assert!(ops_headers.iter().any(|x| x == h), "Operations column {h}");
    }
    let types_headers = headers_of(&mut wb, "Types");
    assert!(types_headers.iter().any(|x| x == "Adjusted Price (EIV)"));

    let root_sheet = op_sheet_names(&wb)[0].clone();
    let trit = op_table_row(&mut wb, &root_sheet, "34");
    for h in [
        "Inventory Unit Basis",
        "Excel Inventory Cost",
        "API Inventory Cost",
        "Fresh Unit Price",
        "Excel Fresh Cost",
        "API Fresh Cost",
        "Excel Requirement Cost",
        "API Requirement Cost",
        "Cost Status",
    ] {
        assert!(trit.contains_key(h), "OP sheet column {h}");
    }
    // No inventory basis seeded -> the 60 units reused have no known
    // unit cost, so the Buy leaf is cost-incomplete, never zeroed.
    assert!(matches!(trit["Inventory Unit Basis"], Data::Empty));
    // 40 units short @ 5 ISK (fixture_prices-equivalent) = 200.
    assert_eq!(cell_f64(&trit["API Fresh Cost"]), Some(200.0));
}
